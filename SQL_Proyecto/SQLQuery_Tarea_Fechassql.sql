--SYSDATETIME
SELECT SYSDATETIME() AS FechaHoraSistema;

--GETDATE
SELECT GETDATE() AS FechaHoraLocal;

-- GETUTCDATE
SELECT GETUTCDATE() AS FechaHoraUTC;

--DATENAME
SELECT DATENAME(WEEKDAY, Fec_Tk) AS DiaSemana FROM Ticket;

--DATEPART
SELECT DATEPART(WEEK, Fec_Tk) AS SemanaDelAño FROM Ticket;

--DAY
SELECT DAY(Fec_Tk) AS DiaVenta FROM Ticket;

--MONTH
SELECT MONTH(Fec_Tk) AS MesVenta FROM Ticket;

--YEAR
SELECT YEAR(Fec_Tk) AS AñoVenta FROM Ticket;

--DATEFROMPARTS
SELECT DATEFROMPARTS(2025, 11, 1) AS FechaPromocion;

--DATETIMEFROMPARTS
SELECT DATETIMEFROMPARTS(2025, 11, 1, 8, 30, 0, 0) AS FechaHoraEntrega;

--SMALLDATETIMEFROMPARTS
SELECT SMALLDATETIMEFROMPARTS(2025, 11, 1, 8, 30) AS FechaHoraEntregaSimple;

--DATEDIFF
SELECT DATEDIFF(DAY, MIN(Fec_Tk), MAX(Fec_Tk)) AS DiasEntreVentas FROM Ticket;

--DATEADD
SELECT DATEADD(DAY, 30, Fec_Tk) AS FechaVencimiento FROM Ticket WHERE Clav_Tk = 1;

